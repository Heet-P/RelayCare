const ALL: Record<Locale, Partial<Messages>> = { en, hi, gu };

/** Messages for a locale, falling back to English for anything not yet translated. */
export function tr(locale: string | null | undefined): Messages {
  const l = (locale === "hi" || locale === "gu" ? locale : "en") as Locale;
  return { ...en, ...ALL[l] } as Messages;
}
