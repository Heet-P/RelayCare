-- RelayCare business rules enforced by Postgres (defense in depth behind the app layer).
--
-- 1. Case state machine: legal (from, to) pairs + trigger.
-- 2. Append-only case_events.
-- 3. updated_at maintenance.
-- 4. Row-level security: READ policies for the `authenticated` role.
--    All WRITES go through server code (owner connection) after app-layer authorization,
--    so no INSERT/UPDATE/DELETE policies exist: direct client writes are always denied.
-- 5. Realtime publication for live dashboards.

