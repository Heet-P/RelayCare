CREATE SCHEMA IF NOT EXISTS app;--> statement-breakpoint
GRANT USAGE ON SCHEMA app TO authenticated;--> statement-breakpoint

-- auth.uid() is provided by Supabase; on plain Postgres (tests) a shim is created below.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'auth') THEN
    CREATE SCHEMA auth;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'auth' AND p.proname = 'uid'
  ) THEN
    EXECUTE $f$
      CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS
      'SELECT nullif(current_setting(''request.jwt.claims'', true)::jsonb ->> ''sub'', '''')::uuid'
    $f$;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    CREATE ROLE authenticated NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    CREATE ROLE anon NOLOGIN;
  END IF;
END $$;--> statement-breakpoint

-- Helper functions are SECURITY DEFINER so policies can consult other tables without
-- recursive RLS evaluation. search_path is pinned to prevent hijacking.
CREATE FUNCTION app.current_user_id() RETURNS uuid
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT u.id FROM public.users u WHERE u.auth_user_id = auth.uid()
$$;--> statement-breakpoint

CREATE FUNCTION app.has_org_role(org uuid, roles public.member_role[]) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.organization_memberships m
    WHERE m.organization_id = org
      AND m.user_id = app.current_user_id()
      AND m.is_active
      AND m.role = ANY (roles)
  )
$$;--> statement-breakpoint

-- Org-wide case visibility: everyone except technicians (who only see their assignments).
CREATE FUNCTION app.is_org_staff(org uuid) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT app.has_org_role(org, ARRAY['owner', 'support_agent', 'dispatcher']::public.member_role[])
$$;--> statement-breakpoint

CREATE FUNCTION app.is_org_member(org uuid) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT app.has_org_role(org, ARRAY['owner', 'support_agent', 'dispatcher', 'technician']::public.member_role[])
$$;--> statement-breakpoint

-- Spec §3: a chat channel ID is not authorization. Case access = org staff,
-- an ACTIVE participant (removed_at IS NULL), or the customer who owns the case.
CREATE FUNCTION app.can_access_case(target uuid) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.service_cases c
    WHERE c.id = target
      AND (
        app.is_org_staff(c.organization_id)
        OR EXISTS (
          SELECT 1 FROM public.case_participants p
          WHERE p.case_id = c.id AND p.user_id = app.current_user_id() AND p.removed_at IS NULL
        )
        OR EXISTS (
          SELECT 1 FROM public.customers cu
          WHERE cu.id = c.customer_id AND cu.user_id = app.current_user_id()
        )
      )
  )
$$;--> statement-breakpoint

CREATE FUNCTION app.owns_customer(target uuid) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.customers cu WHERE cu.id = target AND cu.user_id = app.current_user_id()
  )
$$;--> statement-breakpoint

GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA app TO authenticated;--> statement-breakpoint
GRANT SELECT ON ALL TABLES IN SCHEMA public TO authenticated;--> statement-breakpoint
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA public FROM authenticated, anon;--> statement-breakpoint
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;--> statement-breakpoint

-- Enable RLS everywhere. Tables without a policy are invisible to clients.
DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;--> statement-breakpoint

CREATE POLICY org_read ON public.organizations FOR SELECT TO authenticated
  USING (app.is_org_member(id) OR EXISTS (
    SELECT 1 FROM public.customers cu WHERE cu.organization_id = organizations.id AND cu.user_id = app.current_user_id()
  ));--> statement-breakpoint

-- Self, org colleagues, and people sharing an active case (names in the case/chat UI).
CREATE POLICY users_read ON public.users FOR SELECT TO authenticated
  USING (
    id = app.current_user_id()
    OR EXISTS (
      SELECT 1 FROM public.organization_memberships m
      WHERE m.user_id = users.id AND app.is_org_member(m.organization_id)
    )
    OR EXISTS (
      SELECT 1 FROM public.case_participants mine
      JOIN public.case_participants theirs ON theirs.case_id = mine.case_id
      WHERE mine.user_id = app.current_user_id() AND mine.removed_at IS NULL
        AND theirs.user_id = users.id AND theirs.removed_at IS NULL
    )
  );--> statement-breakpoint

CREATE POLICY memberships_read ON public.organization_memberships FOR SELECT TO authenticated
  USING (user_id = app.current_user_id() OR app.is_org_member(organization_id));--> statement-breakpoint

CREATE POLICY partners_read ON public.service_partners FOR SELECT TO authenticated
