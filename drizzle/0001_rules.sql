CREATE POLICY customers_read ON public.customers FOR SELECT TO authenticated
  USING (user_id = app.current_user_id() OR app.is_org_staff(organization_id));--> statement-breakpoint

CREATE POLICY orders_read ON public.orders FOR SELECT TO authenticated
  USING (app.is_org_staff(organization_id) OR app.owns_customer(customer_id));--> statement-breakpoint

CREATE POLICY order_items_read ON public.order_items FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.orders o
    WHERE o.id = order_items.order_id AND (app.is_org_staff(o.organization_id) OR app.owns_customer(o.customer_id))
