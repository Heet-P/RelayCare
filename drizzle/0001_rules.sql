CREATE FUNCTION public.case_events_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'case_events is append-only' USING ERRCODE = 'insufficient_privilege';
END $$;--> statement-breakpoint

CREATE TRIGGER case_events_no_update
  BEFORE UPDATE OR DELETE ON public.case_events
  FOR EACH ROW EXECUTE FUNCTION public.case_events_append_only();--> statement-breakpoint

