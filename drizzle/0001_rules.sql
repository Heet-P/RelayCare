    -- Technicians reach order items only through a case they can access.
    SELECT 1 FROM public.service_cases c WHERE c.order_item_id = order_items.id AND app.can_access_case(c.id)
  ));--> statement-breakpoint

CREATE POLICY warranties_read ON public.warranties FOR SELECT TO authenticated
  USING (EXISTS (SELECT 1 FROM public.order_items oi WHERE oi.id = warranties.order_item_id));--> statement-breakpoint

CREATE POLICY cases_read ON public.service_cases FOR SELECT TO authenticated
