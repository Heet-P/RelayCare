CREATE FUNCTION public.enforce_case_status() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.status <> 'submitted' THEN
      RAISE EXCEPTION 'New cases must start as submitted (got %)', NEW.status USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.status IS DISTINCT FROM OLD.status AND NOT EXISTS (
    SELECT 1 FROM public.case_status_transitions t
    WHERE t.from_status = OLD.status AND t.to_status = NEW.status
  ) THEN
    RAISE EXCEPTION 'Illegal case transition % -> %', OLD.status, NEW.status USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;--> statement-breakpoint

CREATE TRIGGER service_cases_status_guard
  BEFORE INSERT OR UPDATE OF status ON public.service_cases
  FOR EACH ROW EXECUTE FUNCTION public.enforce_case_status();--> statement-breakpoint

